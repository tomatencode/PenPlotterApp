function rawToPlotterStrokes(rawStrokes: number[][][]): PlotterStroke[] {
  return rawStrokes.map((pts) => {
    const start: [number, number] = [pts[0][0], pts[0][1]];
    const moves: PlotterMove[] = pts.slice(1).map((pt, i) => ({
      type:  "Line" as const,
      x1: pts[i][0], y1: pts[i][1],
      x2: pt[0],     y2: pt[1],
    }));
    return { start, moves };
  });
}

